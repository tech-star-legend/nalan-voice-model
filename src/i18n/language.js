const originalText = new WeakMap();

export function translateDom(language) {
  document.documentElement.lang = language === "en" ? "en-IN" : "ta-IN";
  document.documentElement.dir = "ltr";
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest("script,style,noscript")) continue;
    nodes.push(node);
  }
  nodes.forEach((textNode) => {
    if (!originalText.has(textNode)) originalText.set(textNode, textNode.nodeValue);
    const source = originalText.get(textNode);
    if (language === "ta") {
      textNode.nodeValue = source;
      return;
    }
    const exact = translations[source.trim()];
    if (exact) {
      const leading = source.match(/^\s*/)?.[0] || "";
      const trailing = source.match(/\s*$/)?.[0] || "";
      textNode.nodeValue = leading + exact + trailing;
      return;
    }
    let result = source;
    Object.entries(translations).forEach(([ta, en]) => {
      if (result.includes(ta)) result = result.split(ta).join(en);
    });
    textNode.nodeValue = result;
  });
}
